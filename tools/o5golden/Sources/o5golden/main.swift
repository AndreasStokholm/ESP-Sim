// Prints test/host/golden_o5.h: OmnipodKit's Omnipod 5 pairing and transport
// computations (the phone's side) on fixed inputs.
import CryptoKit
import CryptoSwift
import Foundation

var out = ""

func arr(_ name: String, _ d: Data) {
    out += "static const uint8_t \(name)[\(d.count)] = {"
    for (i, b) in d.enumerated() {
        if i % 16 == 0 { out += "\n    " }
        out += String(format: "0x%02x,", b)
    }
    out += "\n};\n"
}

func seq(_ n: Int, _ start: UInt8) -> Data { Data((0..<n).map { start &+ UInt8(truncatingIfNeeded: $0) }) }

// Fixed keys and nonces instead of random ones.
let pdmPriv = Data(repeating: 0x11, count: 32)
let podPriv = Data(repeating: 0x22, count: 32)
let pdmNonce = seq(16, 0x30)
let podNonce = seq(16, 0x50)

struct FixedKeys: PrivateKeyGenerator {
    func generatePrivateKey() -> Data { pdmPriv }
    func publicFromPrivate(_ privateKey: Data) throws -> Data { try P256KeyGenerator().publicFromPrivate(privateKey) }
    func computeSharedSecret(_ privateKey: Data, _ publicKey: Data) throws -> Data {
        try P256KeyGenerator().computeSharedSecret(privateKey, publicKey)
    }
}

class FixedRandom: RandomByteGenerator {
    func nextBytes(length: Int) -> Data { pdmNonce.prefix(length) }
}

func ccmEncrypt(_ key: Data, _ nonce: Data, _ pt: Data) throws -> Data {
    let ccm = CCM(iv: Array(nonce), tagLength: 8, messageLength: pt.count)
    return Data(try AES(key: Array(key), blockMode: ccm, padding: .noPadding).encrypt(Array(pt)))
}

func ccmDecrypt(_ key: Data, _ nonce: Data, _ ct: Data) throws -> Data {
    let ccm = CCM(iv: Array(nonce), tagLength: 8, messageLength: ct.count - 8)
    return Data(try AES(key: Array(key), blockMode: ccm, padding: .noPadding).decrypt(Array(ct)))
}

func pairMessage(_ seqNo: UInt8, _ keys: [String], _ payloads: [Data]) -> Data {
    PairMessage(sequenceNumber: seqNo, source: Id.fromUInt32(0x1700_2c00), destination: Id.fromUInt32(0xffff_fffe),
                keys: keys, payloads: payloads).message.asData()
}

func packets(_ name: String, _ payload: Data) {
    var flat = Data()
    for p in PayloadSplitter(payload: payload, layout: o5Layout).splitInPackets() {
        let d = p.toData(layout: o5Layout)
        flat.append(UInt8(d.count >> 8))
        flat.append(UInt8(d.count & 0xff))
        flat.append(d)
    }
    arr(name + "_MSG", payload)
    arr(name + "_PKTS", flat) // each packet: 2-byte length, then the packet
    // And the phone reads them back.
    let pk = PayloadSplitter(payload: payload, layout: o5Layout).splitInPackets().map { $0.toData(layout: o5Layout) }
    let j = try! PayloadJoiner(firstPacket: pk[0], layout: o5Layout)
    for p in pk.dropFirst() { try! j.accumulate(packet: p) }
    precondition(try! j.finalize() == payload)
}

out += "/* Generated by tools/o5golden from OmnipodKit's Omnipod 5 code. Do not edit. */\n"
out += "#pragma once\n#include <stdint.h>\n#include <stddef.h>\n\n"

// ---- key exchange --------------------------------------------------------
let ke = try O5KeyExchange(FixedKeys(), FixedRandom(), controllerIdData: Data([0x17, 0x00, 0x2c, 0x00]))
let podPub = try P256KeyGenerator().publicFromPrivate(podPriv)
// CryptoKit may hand back a Data slice; OmnipodKit indexes from 0.
try ke.o5updatePodPublicData(Data(Array(podPub) + Array(podNonce)))
arr("O5_PDM_PRIV", pdmPriv)
arr("O5_PDM_PUB", ke.pdmPublic)
arr("O5_POD_PRIV", podPriv)
arr("O5_POD_PUB", podPub)
arr("O5_PDM_NONCE", pdmNonce)
arr("O5_POD_NONCE", podNonce)
arr("O5_SHARED", try P256KeyGenerator().computeSharedSecret(podPriv, ke.pdmPublic))
arr("O5_CONF", ke.conf)
arr("O5_LTK", ke.ltk)
arr("O5_FIRMWARE_ID", O5LTKExchanger.FIRMWARE_ID)

// ---- the certificate exchange, in the phone's order -----------------------
let phoneCert21 = Data(repeating: 0xc1, count: 634)
let phoneCert2 = Data(repeating: 0xc2, count: 300) + Data(repeating: 0x5a, count: 64)
let podCert21 = Data(repeating: 0xd1, count: 333)
let podCert2 = Data(repeating: 0xd2, count: 333) + Data(repeating: 0xa5, count: 64)

let nW0 = ke.getSPSNonce(direction: .write)
let ctPhone21 = try ccmEncrypt(ke.conf, nW0, phoneCert21)
ke.incrementNonce(direction: .write)
let nR0 = ke.getSPSNonce(direction: .read)
let ctPod21 = try ccmEncrypt(ke.conf, nR0, podCert21)
let backPod21 = try ccmDecrypt(ke.conf, nR0, ctPod21)
precondition(backPod21 == podCert21)
ke.incrementNonce(direction: .read)
let phoneTranscript = ke.buildChannelBindingTranscript()
let nW1 = ke.getSPSNonce(direction: .write)
let ctPhone2 = try ccmEncrypt(ke.conf, nW1, phoneCert2)
ke.incrementNonce(direction: .write)
let nR1 = ke.getSPSNonce(direction: .read)
let ctPod2 = try ccmEncrypt(ke.conf, nR1, podCert2)
ke.incrementNonce(direction: .read)
let podTranscript = ke.buildPodChannelBindingTranscript()

for (n, d) in [("W0", nW0), ("R0", nR0), ("W1", nW1), ("R1", nR1)] { arr("O5_SPS_NONCE_" + n, d) }
arr("O5_PHONE_CERT21", phoneCert21)
arr("O5_PHONE_CERT2", phoneCert2)
arr("O5_POD_CERT21", podCert21)
arr("O5_POD_CERT2", podCert2)
arr("O5_CT_PHONE21", ctPhone21)
arr("O5_CT_POD21", ctPod21)
arr("O5_CT_PHONE2", ctPhone2)
arr("O5_CT_POD2", ctPod2)
arr("O5_PHONE_TRANSCRIPT", phoneTranscript)
arr("O5_POD_TRANSCRIPT", podTranscript)

// ---- pairing messages as the phone sends them -----------------------------
let sp2 = Data([0x00, 0x00, 0x10, 0x25, 0x00, 0x03, 0x0e, 0x01, 0x00, 0x81, 0x29])
var sps0 = Data([0x00, 0x01, 0x09])
sps0.appendBigEndian(O5LTKExchanger.crc16XMODEM(sps0))
var podSps0 = Data([0x00, 0x00, 0x09])
podSps0.appendBigEndian(O5LTKExchanger.crc16XMODEM(podSps0))
arr("O5_MSG_SP1SP2", pairMessage(1, ["SP1=", ",SP2="], [Data([0x00, 0x00, 0x10, 0x25]), sp2]))
arr("O5_MSG_SPS0", pairMessage(2, ["SPS0="], [sps0]))
arr("O5_POD_SPS0_VALUE", podSps0)
arr("O5_MSG_SPS1", pairMessage(3, ["SPS1="], [ke.pdmPublic + pdmNonce]))
arr("O5_MSG_SPS21", pairMessage(4, ["SPS2.1="], [ctPhone21]))
arr("O5_MSG_SPS2", pairMessage(5, ["SPS2="], [ctPhone2]))
arr("O5_MSG_SP0GP0", pairMessage(6, ["SP0,GP0"], [Data()]))

// ---- packets at 244 bytes ---------------------------------------------------
var names: [String] = []
for n in [10, 237, 238, 239, 242, 243, 244, 300, 480, 481, 485, 486, 700, 1105] {
    let name = "O5_FRAG_\(n)"
    packets(name, seq(n, 0x40))
    names.append(name)
}
out += "static const struct { const uint8_t *msg; size_t msg_len; const uint8_t *pkts; size_t pkts_len; } O5_FRAGS[] = {\n"
for n in names { out += "    {\(n)_MSG, sizeof \(n)_MSG, \(n)_PKTS, sizeof \(n)_PKTS},\n" }
out += "};\n#define O5_FRAG_COUNT \(names.count)\n"

// ---- a signed (Type 4) command, and the response CRC ------------------------
let ck = seq(16, 0x70)
let prefix = seq(8, 0x90)
let wrapped = StringLengthPrefixEncoding.formatKeys(keys: ["S0.0=", ",G0.0"],
                                                    payloads: [Data(hex: "fffffffe0c071f05494e532e070000"), Data()])
let cmd = MessagePacket(type: .ENCRYPTED_SIGNED, source: 0x1700_2c00, destination: 0x0000_1025, payload: wrapped,
                        sequenceNumber: 9, eqos: 1)
var signed = try EnDecrypt(nonce: Nonce(prefix: prefix), ck: ck).encrypt(cmd, 5)
signed.signatureData = Data(repeating: 0xee, count: 64)
arr("O5_CK", ck)
arr("O5_NONCE_PREFIX", prefix)
arr("O5_SIGNED_CMD", signed.asData())
arr("O5_SIGNED_CMD_PLAIN", wrapped)

for (i, s) in ["1d1800a02800000463ff", "0115040a00010300040208146db10006e45100ffffffff"].enumerated() {
    let d = Data(hex: s)
    out += String(format: "#define O5_CRC16_%d 0x%04x /* %@ */\n", i, d.crc16(), s)
}

// ---- the AID setup commands, as sent ---------------------------------------
let aids: [(String, (data: Data, responsePrefix: String))] = [
    ("UTC", O5AidCommands.UtcCommand.payload(timestamp: 1_789_000_000)),
    ("TDI", O5AidCommands.TdiCommand.payload()),
    ("TARGET", O5AidCommands.TargetBgProfileCommand.payload()),
    ("DIA", O5AidCommands.DiaCommand.payload()),
    ("EGV", O5AidCommands.EgvCommand.payload()),
    ("HISTORY", O5AidCommands.AlgorithmInsulinHistoryCommand.payload()),
    ("STATUS", O5AidCommands.AidPodStatusCommand.payload()),
    ("UNIFIED", O5AidCommands.UnifiedAidPodStatusCommand.payload()),
]
for (n, p) in aids {
    arr("O5_AID_\(n)", p.data)
    out += "#define O5_AID_\(n)_PREFIX \"\(p.responsePrefix)\"\n"
}

FileHandle.standardOutput.write(out.data(using: .utf8)!)
